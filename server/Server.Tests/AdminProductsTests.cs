using System.Net;
using System.Net.Http.Headers;
using System.Net.Http.Json;
using Microsoft.EntityFrameworkCore;
using Server.Api.Controllers;
using Server.Api.Models;
using Server.Api.Models.Dto;

namespace Server.Tests;

// Project 6: the admin product API against a real (throwaway) SQL Server database
public class AdminProductsTests(ApiFactory factory) : IClassFixture<ApiFactory>
{
    private const string Url = "/api/admin/products";

    private async Task<HttpClient> As(string email, string password)
    {
        var anon = factory.CreateClient();
        var login = await anon.PostAsJsonAsync("/api/auth/login", new LoginDto(email, password));
        var token = (await login.Content.ReadFromJsonAsync<ApiResponse<LoginResultDto>>())!.Data!.AccessToken;
        var client = factory.CreateClient();
        client.DefaultRequestHeaders.Authorization = new AuthenticationHeaderValue("Bearer", token);
        return client;
    }
    private Task<HttpClient> Admin() => As("admin@redstar.dev", "Admin@123");

    private static async Task<AdminProductDto> Read(HttpResponseMessage r) =>
        (await r.Content.ReadFromJsonAsync<ApiResponse<AdminProductDto>>())!.Data!;

    private async Task<AdminProductDto> CreateProduct(HttpClient admin, string name, decimal price = 5m)
    {
        var response = await admin.PostAsJsonAsync(Url, new SaveProductDto(name, "Test item", price, 3));
        Assert.Equal(HttpStatusCode.Created, response.StatusCode);
        return await Read(response);
    }

    [Fact]
    public async Task OnlyAdmins_Anonymous401_Customer403()
    {
        Assert.Equal(HttpStatusCode.Unauthorized, (await factory.CreateClient().GetAsync(Url)).StatusCode);
        var customer = await As("asha@redstar.dev", "Customer@123");
        Assert.Equal(HttpStatusCode.Forbidden, (await customer.PostAsJsonAsync(Url, new SaveProductDto("X", null, 1, 1))).StatusCode);
    }

    [Fact]
    public async Task Create_IsSavedToSql_AndShowsUpInThePublicCatalogue()
    {
        var admin = await Admin();
        var created = await CreateProduct(admin, "Masala Chai", 2.25m);

        Assert.True(created.Id > 11);
        Assert.False(string.IsNullOrEmpty(created.RowVersion)); // generated by SQL Server
        var publicView = await factory.CreateClient().GetFromJsonAsync<ApiResponse<ProductDto>>($"/api/products/{created.Id}");
        Assert.Equal(("Masala Chai", 2.25m, "Drinks"), (publicView!.Data!.Name, publicView.Data.Price, publicView.Data.CategoryName));
    }

    [Fact]
    public async Task Create_Invalid_Is400_PerField_AndUnknownCategory()
    {
        var admin = await Admin();
        var bad = await admin.PostAsJsonAsync(Url, new { name = "", price = 0, categoryId = 0 });
        var body = await bad.Content.ReadFromJsonAsync<ApiResponse<object>>();
        Assert.Equal(HttpStatusCode.BadRequest, bad.StatusCode);
        Assert.True(body!.FieldErrors!.Keys.ToHashSet().IsSupersetOf(["name", "price", "categoryId"]));

        var unknown = await admin.PostAsJsonAsync(Url, new SaveProductDto("Thing", null, 1, 999));
        Assert.Equal(["That category doesn't exist."], (await unknown.Content.ReadFromJsonAsync<ApiResponse<object>>())!.FieldErrors!["categoryId"]);
    }

    [Fact]
    public async Task Update_WithTheCurrentRowVersion_Succeeds_AndChangesTheRowVersion()
    {
        var admin = await Admin();
        var p = await CreateProduct(admin, "Filter Coffee");

        var response = await admin.PutAsJsonAsync($"{Url}/{p.Id}", new SaveProductDto("Filter Coffee (large)", "Strong", 4m, 3, true, p.RowVersion));

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        var updated = await Read(response);
        Assert.Equal("Filter Coffee (large)", updated.Name);
        Assert.NotEqual(p.RowVersion, updated.RowVersion); // SQL Server bumped it
        Assert.NotNull(updated.UpdatedAt);
    }

    [Fact]
    public async Task Update_WithAStaleRowVersion_Is409_AndNothingIsOverwritten()
    {
        var admin = await Admin();
        var p = await CreateProduct(admin, "Rose Falooda", 4m);

        // Two admins loaded the SAME version. The first one saves...
        var first = await admin.PutAsJsonAsync($"{Url}/{p.Id}", new SaveProductDto("Rose Falooda", null, 4.5m, 4, true, p.RowVersion));
        Assert.Equal(HttpStatusCode.OK, first.StatusCode);

        // ...then the second saves using the OLD rowVersion: it must be refused, not silently overwrite the first
        var second = await admin.PutAsJsonAsync($"{Url}/{p.Id}", new SaveProductDto("Rose Falooda", null, 1m, 4, true, p.RowVersion));
        Assert.Equal(HttpStatusCode.Conflict, second.StatusCode);

        var now = await factory.WithDbAsync(db => db.Products.AsNoTracking().SingleAsync(x => x.Id == p.Id));
        Assert.Equal(4.5m, now.Price); // the first admin's change survived
    }

    [Theory]
    [InlineData(null)]
    [InlineData("not-base64!!")]
    public async Task Update_WithoutAValidRowVersion_Is400(string? rowVersion)
    {
        var admin = await Admin();
        var response = await admin.PutAsJsonAsync($"{Url}/1", new SaveProductDto("Classic Burger", null, 8.5m, 1, true, rowVersion));
        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
    }

    [Fact]
    public async Task Delete_IsSoft_HiddenByTheGlobalQueryFilter_ButStillInTheDatabase()
    {
        var admin = await Admin();
        var p = await CreateProduct(admin, "Seasonal Special");

        Assert.Equal(HttpStatusCode.NoContent, (await admin.DeleteAsync($"{Url}/{p.Id}")).StatusCode);

        Assert.Equal(HttpStatusCode.NotFound, (await factory.CreateClient().GetAsync($"/api/products/{p.Id}")).StatusCode); // public: gone
        var adminView = await Read(await admin.GetAsync($"{Url}/{p.Id}"));
        Assert.False(adminView.IsActive); // admin (IgnoreQueryFilters): still there, marked inactive
        Assert.True(await factory.WithDbAsync(db => db.Products.IgnoreQueryFilters().AnyAsync(x => x.Id == p.Id)));
        Assert.False(await factory.WithDbAsync(db => db.Products.AnyAsync(x => x.Id == p.Id))); // the filter applies everywhere
    }

    // ---------- image upload ----------
    private static readonly byte[] PngHeader = [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A];

    private static MultipartFormDataContent FileForm(byte[] bytes, string fileName, string contentType)
    {
        var file = new ByteArrayContent(bytes);
        file.Headers.ContentType = new MediaTypeHeaderValue(contentType);
        return new MultipartFormDataContent { { file, "file", fileName } };
    }

    [Fact]
    public async Task UploadImage_Png_IsSavedWithARandomName_ServedWithCacheHeaders_AndReplacesTheOld()
    {
        var admin = await Admin();
        var p = await CreateProduct(admin, "Photo Product");
        byte[] png = [.. PngHeader, .. new byte[100]];

        var first = await Read(await admin.PostAsync($"{Url}/{p.Id}/image", FileForm(png, "../../evil.png", "image/png")));
        Assert.Matches(@"^/images/products/[0-9a-f]{32}\.png$", first.ImageUrl!); // OUR name: the client's path is ignored

        var served = await factory.CreateClient().GetAsync(first.ImageUrl);
        Assert.Equal(HttpStatusCode.OK, served.StatusCode);
        Assert.Contains("immutable", served.Headers.CacheControl!.ToString());

        var second = await Read(await admin.PostAsync($"{Url}/{p.Id}/image", FileForm(png, "new.png", "image/png")));
        Assert.NotEqual(first.ImageUrl, second.ImageUrl);
        Assert.Equal(HttpStatusCode.NotFound, (await factory.CreateClient().GetAsync(first.ImageUrl)).StatusCode); // old file deleted
        Assert.Single(Directory.GetFiles(factory.ImagesPath));
    }

    [Theory]
    [InlineData("script.png", "image/png", "This is not an image")] // the name and Content-Type LIE: the bytes decide
    [InlineData("doc.pdf", "application/pdf", "%PDF-1.7")]
    public async Task UploadImage_ChecksTheRealContent_NotTheNameOrContentType(string name, string type, string content)
    {
        var admin = await Admin();
        var response = await admin.PostAsync($"{Url}/1/image", FileForm(System.Text.Encoding.UTF8.GetBytes(content), name, type));

        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
        Assert.Equal(["Only JPEG, PNG or WebP images are allowed."], (await response.Content.ReadFromJsonAsync<ApiResponse<object>>())!.FieldErrors!["file"]);
    }

    [Fact]
    public async Task UploadImage_TooLarge_Is400()
    {
        var admin = await Admin();
        byte[] big = [.. PngHeader, .. new byte[2 * 1024 * 1024]]; // just over 2 MB
        var response = await admin.PostAsync($"{Url}/1/image", FileForm(big, "big.png", "image/png"));

        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
        Assert.Equal(["The image must be 2 MB or smaller."], (await response.Content.ReadFromJsonAsync<ApiResponse<object>>())!.FieldErrors!["file"]);
    }
}
